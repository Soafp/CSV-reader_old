import streamlit as st
from tools import read_csv
from chat import init_chat, chat


st.set_page_config(layout="wide", page_title="CSV Chatbot", page_icon="📊")
st.title("CSV Chatbot")
st.markdown("""
<style>
.stChatInput textarea:focus {
    border-color: rgba(255, 255, 255, 0.2) !important;
    box-shadow: none !important;
}
.stChatInput textarea {
    border-color: rgba(255, 255, 255, 0.1) !important;
}
.stChatInput > div {
    border-color: rgba(255, 255, 255, 0.1) !important;
}
[data-testid="stChatInput"] > div {
    border-color: rgba(255, 255, 255, 0.15) !important;
    box-shadow: none !important;
}
</style>
""", unsafe_allow_html=True)

# Init session state once
if "messages" not in st.session_state:
    st.session_state.messages = []
if "figs" not in st.session_state:
    st.session_state.figs = []
if "chat_history" not in st.session_state:
    st.session_state.chat_history = []
if "chart_counter" not in st.session_state:
    st.session_state.chart_counter = 0

uploaded = st.file_uploader("Upload CSV", type=["csv"])

if uploaded:
    df = read_csv(uploaded)

    if len(st.session_state.messages) == 0:
        init_chat(df)

    with st.sidebar:
        st.divider()
        if st.button("🔄 Reset chat", key="reset_chat"):
            st.session_state.messages = []
            st.session_state.chat_history = []
            st.session_state.figs = []
            st.session_state.chart_counter = 0
            st.rerun()

    # ── TWO COLUMN LAYOUT ─────────────────────────────
    left_col, right_col = st.columns([1, 1])

    with left_col:
        st.subheader("Chat")
        chat_container = st.container(height=500)
        with chat_container:
            for role, text in st.session_state.chat_history:
                with st.chat_message(role):
                    st.write(text)

        if prompt := st.chat_input("Ask about your data…"):
            st.session_state.chat_history.append(("user", prompt))
            with st.chat_message("user"):
                st.write(prompt)

            with st.chat_message("assistant"):
                with st.spinner("Thinking…"):
                    reply = chat(prompt, df)
                st.write(reply)
                st.session_state.chat_history.append(("assistant", reply))

            st.rerun()

    with right_col:
        st.subheader("Charts")
        if st.session_state.figs:
            if len(st.session_state.figs) >= 2:
                if st.button("🗑 Clear all charts", key="clear_all"):
                    st.session_state.figs = []
                    st.rerun()
            for i, (fig, title, chart_id) in enumerate(st.session_state.figs):
                st.plotly_chart(fig, use_container_width=True, key=f"chart_{chart_id}")
                if st.button(f"🗑 Delete {title}", key=f"del_{chart_id}"):
                    st.session_state.figs.pop(i)
                    st.rerun()
        else:
            st.info("Charts generated by the AI will appear here.")